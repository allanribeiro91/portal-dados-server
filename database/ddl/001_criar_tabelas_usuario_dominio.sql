/* CRIAÇÃO DO SCHEMA */
CREATE SCHEMA IF NOT EXISTS SCPORTALDADOS;

/* CONFIGURAÇÃO DO SCHEMA */
SET SEARCH_PATH TO SCPORTALDADOS;

/* CONFIGURAÇÃO DE DATA */
SET DATESTYLE = DMY;

BEGIN;

/* ============================================================
   TABELA DE DOMÍNIOS
   ============================================================ */
CREATE TABLE TB_DOMINIO (
    CO_SEQ_DOMINIO  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CO_DOMINIO      BIGINT,
    NO_DOMINIO      VARCHAR(100) NOT NULL,
    DS_DOMINIO      VARCHAR(500),
    DS_OBSERVACOES  TEXT,

    CONSTRAINT PK_TB_DOMINIO
        PRIMARY KEY (CO_SEQ_DOMINIO),
    CONSTRAINT FK_TB_DOMINIO_DOMINIO_PAI
        FOREIGN KEY (CO_DOMINIO)
        REFERENCES TB_DOMINIO (CO_SEQ_DOMINIO)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    CONSTRAINT CK_TB_DOMINIO_AUTORRELACIONAMENTO
        CHECK (CO_DOMINIO IS NULL OR CO_DOMINIO <> CO_SEQ_DOMINIO)
);

/* Impede nomes repetidos no mesmo agrupamento, inclusive na raiz. */
CREATE UNIQUE INDEX UQ_TB_DOMINIO_NOME_POR_GRUPO
    ON TB_DOMINIO (COALESCE(CO_DOMINIO, 0), LOWER(NO_DOMINIO));

COMMENT ON TABLE TB_DOMINIO IS
    'Mantém os agrupamentos e valores de domínio utilizados pela aplicação.';
COMMENT ON COLUMN TB_DOMINIO.CO_SEQ_DOMINIO IS
    'Identificador único do domínio.';
COMMENT ON COLUMN TB_DOMINIO.CO_DOMINIO IS
    'Domínio pai. Deve ser nulo para os agrupadores de primeiro nível.';
COMMENT ON COLUMN TB_DOMINIO.NO_DOMINIO IS
    'Nome do agrupador ou do valor de domínio.';


/* ============================================================
   TABELA DE USUÁRIOS
   ============================================================ */
CREATE TABLE TB_USUARIO (
    CO_SEQ_USUARIO          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CO_CPF                  VARCHAR(11) NOT NULL,
    NO_NOME                 VARCHAR(200) NOT NULL,
    DS_EMAIL                VARCHAR(254) NOT NULL,
    DS_CELULAR              VARCHAR(20),
    DS_SENHA                VARCHAR(255) NOT NULL,
    DT_REGISTRO             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DT_ULTIMA_ATUALIZACAO   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CO_STATUS               BIGINT NOT NULL,
    CO_TP_USUARIO           BIGINT NOT NULL,

    CONSTRAINT PK_TB_USUARIO
        PRIMARY KEY (CO_SEQ_USUARIO),
    CONSTRAINT UQ_TB_USUARIO_CPF
        UNIQUE (CO_CPF),
    CONSTRAINT FK_TB_USUARIO_STATUS
        FOREIGN KEY (CO_STATUS)
        REFERENCES TB_DOMINIO (CO_SEQ_DOMINIO)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    CONSTRAINT FK_TB_USUARIO_TIPO
        FOREIGN KEY (CO_TP_USUARIO)
        REFERENCES TB_DOMINIO (CO_SEQ_DOMINIO)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    CONSTRAINT CK_TB_USUARIO_CPF_FORMATO
        CHECK (CO_CPF ~ '^[0-9]{11}$'),
    CONSTRAINT CK_TB_USUARIO_NOME
        CHECK (LENGTH(BTRIM(NO_NOME)) >= 2),
    CONSTRAINT CK_TB_USUARIO_EMAIL
        CHECK (DS_EMAIL ~* '^[A-Z0-9._%+\-]+@[A-Z0-9.\-]+\.[A-Z]{2,}$'),
    CONSTRAINT CK_TB_USUARIO_SENHA_HASH
        CHECK (LENGTH(BTRIM(DS_SENHA)) >= 20)
);

/* E-mail único sem diferenciar letras maiúsculas e minúsculas. */
CREATE UNIQUE INDEX UQ_TB_USUARIO_EMAIL_LOWER
    ON TB_USUARIO (LOWER(DS_EMAIL));

CREATE INDEX IX_TB_USUARIO_STATUS
    ON TB_USUARIO (CO_STATUS);

CREATE INDEX IX_TB_USUARIO_TIPO
    ON TB_USUARIO (CO_TP_USUARIO);

COMMENT ON TABLE TB_USUARIO IS
    'Mantém os dados cadastrais, credenciais e nível de acesso dos usuários.';
COMMENT ON COLUMN TB_USUARIO.CO_CPF IS
    'CPF contendo somente os 11 algarismos. Os dígitos verificadores serão validados pela aplicação.';
COMMENT ON COLUMN TB_USUARIO.DS_SENHA IS
    'Hash da senha. Nunca deve armazenar a senha original em texto puro.';
COMMENT ON COLUMN TB_USUARIO.CO_STATUS IS
    'Referência a um valor filho do domínio Status do Usuário.';
COMMENT ON COLUMN TB_USUARIO.CO_TP_USUARIO IS
    'Referência a um valor filho do domínio Tipo de Usuário.';


/* ============================================================
   ATUALIZAÇÃO AUTOMÁTICA DA DATA DE ALTERAÇÃO
   ============================================================ */
CREATE OR REPLACE FUNCTION FN_TB_USUARIO_ATUALIZAR_DATA()
RETURNS TRIGGER
LANGUAGE PLPGSQL
AS $$
BEGIN
    NEW.DT_ULTIMA_ATUALIZACAO := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER TG_TB_USUARIO_ATUALIZAR_DATA
BEFORE UPDATE ON TB_USUARIO
FOR EACH ROW
EXECUTE FUNCTION FN_TB_USUARIO_ATUALIZAR_DATA();


/* ============================================================
   VALIDAÇÃO DOS AGRUPAMENTOS DE DOMÍNIO
   ============================================================ */
CREATE OR REPLACE FUNCTION FN_TB_USUARIO_VALIDAR_DOMINIOS()
RETURNS TRIGGER
LANGUAGE PLPGSQL
AS $$
DECLARE
    V_DOMINIO_PAI_STATUS VARCHAR(100);
    V_DOMINIO_PAI_TIPO   VARCHAR(100);
BEGIN
    SELECT PAI.NO_DOMINIO
      INTO V_DOMINIO_PAI_STATUS
      FROM TB_DOMINIO VALOR
      JOIN TB_DOMINIO PAI
        ON PAI.CO_SEQ_DOMINIO = VALOR.CO_DOMINIO
     WHERE VALOR.CO_SEQ_DOMINIO = NEW.CO_STATUS;

    IF V_DOMINIO_PAI_STATUS IS DISTINCT FROM 'Status do Usuário' THEN
        RAISE EXCEPTION
            'CO_STATUS deve referenciar um valor do domínio Status do Usuário';
    END IF;

    SELECT PAI.NO_DOMINIO
      INTO V_DOMINIO_PAI_TIPO
      FROM TB_DOMINIO VALOR
      JOIN TB_DOMINIO PAI
        ON PAI.CO_SEQ_DOMINIO = VALOR.CO_DOMINIO
     WHERE VALOR.CO_SEQ_DOMINIO = NEW.CO_TP_USUARIO;

    IF V_DOMINIO_PAI_TIPO IS DISTINCT FROM 'Tipo de Usuário' THEN
        RAISE EXCEPTION
            'CO_TP_USUARIO deve referenciar um valor do domínio Tipo de Usuário';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER TG_TB_USUARIO_VALIDAR_DOMINIOS
BEFORE INSERT OR UPDATE OF CO_STATUS, CO_TP_USUARIO ON TB_USUARIO
FOR EACH ROW
EXECUTE FUNCTION FN_TB_USUARIO_VALIDAR_DOMINIOS();

COMMIT;
